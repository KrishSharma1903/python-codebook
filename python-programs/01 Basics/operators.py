## Arithmatic Operator
a = 10
b = 5

add = a + b # addition 
sub = a - b # subtraction 
mul = a * b # multiplication
div = a / b # division 
floor_div = a // b # floor division -> result as integer
modulus = a % b # modulus -> gives remainder 
expo =  a ** b # exponential -> a^b

print(add)
print(sub)
print(mul)
print(div)
print(floor_div)
print(modulus)
print(expo)


